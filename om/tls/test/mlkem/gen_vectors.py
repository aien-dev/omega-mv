# Test tooling only (no primitive is implemented here): converts the upstream vector sources into the
# flat record files driver.om reads. Usage, from the omega-mv root:
#   python3 om/tls/test/mlkem/gen_vectors.py WYCHEPROOF_DIR NIST_DIR ACVP_DIR
# Inputs:
#   WYCHEPROOF_DIR/testvectors_v1/mlkem_768_{keygen_seed,encaps,semi_expanded_decaps,}_test.json
#     (C2SP/wycheproof d17cc89f)
#   NIST_DIR/SHA3_{256,512}{ShortMsg,LongMsg}.rsp, SHAKE{128,256}{ShortMsg,LongMsg,VariableOut}.rsp
#     (CAVP sha-3bytetestvectors.zip, shakebytetestvectors.zip)
#   ACVP_DIR/gen-val/json-files/ML-KEM-{keyGen,encapDecap}-FIPS203/internalProjection.json
#     (usnistgov/ACVP-Server 975de31e)
# Every numberOfTests / per-group count is asserted, so a silently shrunk source fails here.
# The expected return codes are derived from the published result plus the length rules of the
# library API (2 = bad length, 1 = ek modulus check, 3 = dk hash check) and asserted per reason.
import hashlib
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
VEC = os.path.join(HERE, "vectors")
EK, DK, CT = 1184, 2400, 1088


def sha256_file(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def hx(s):
    return s if s else "-"


def blen(h):
    assert len(h) % 2 == 0, h[:20]
    return len(h) // 2


def write(name, header, recs):
    recs = [r.lower() for r in recs]  # ACVP hex is uppercase; record letters are restored below
    recs = [r[0].upper() + r[1:] for r in recs]
    with open(os.path.join(VEC, name), "w") as f:
        for h in header:
            f.write("# " + h + "\n")
        for r in recs:
            f.write(r + "\n")
    print(f"{name}: {len(recs)} records")


def wycheproof(wdir):
    base = os.path.join(wdir, "testvectors_v1")
    recs, hdr = [], [
        "Wycheproof ML-KEM-768 vectors (C2SP/wycheproof d17cc89f, Apache-2.0: WYCHEPROOF.LICENSE).",
        "Generated by gen_vectors.py. Record formats: see driver.om."]
    counts = {}

    def load(n):
        p = os.path.join(base, n)
        j = json.load(open(p))
        tests = [t for g in j["testGroups"] for t in g["tests"]]
        assert len(tests) == j["numberOfTests"], n
        hdr.append(f"{n} sha256 {sha256_file(p)} numberOfTests {len(tests)}")
        counts[n] = len(tests)
        return tests

    for t in load("mlkem_768_keygen_seed_test.json"):
        assert t["result"] == "valid" and blen(t["seed"]) == 64
        recs.append(f"Q 0 {t['seed']} {t['ek']} {t['dk']}")
    for t in load("mlkem_768_encaps_test.json"):
        assert blen(t["m"]) == 32
        if t["result"] == "valid":
            recs.append(f"E 0 {t['ek']} {t['m']} {t['c']} {t['K']}")
        else:
            rc = 2 if blen(t["ek"]) != EK else 1
            recs.append(f"E {rc} {t['ek']} {t['m']} - -")
    for t in load("mlkem_768_semi_expanded_decaps_test.json"):
        if t["result"] == "valid":
            rc = 0
        elif blen(t["dk"]) != DK or blen(t["c"]) != CT:
            rc = 2
        else:
            rc = 3
        recs.append(f"D {rc} {t['dk']} {t['c']} {hx(t['K']) if rc == 0 else '-'}")
    for t in load("mlkem_768_test.json"):
        if blen(t["seed"]) != 64:
            assert t["result"] == "invalid"
            recs.append(f"C 2 {t['seed']} - - 0 -")
            continue
        if t["result"] == "valid":
            r2 = 0
        else:
            assert blen(t["c"]) != CT, t["tcId"]
            r2 = 2
        recs.append(f"C 0 {t['seed']} {hx(t['ek'])} {t['c']} {r2} {hx(t['K']) if r2 == 0 else '-'}")
    write("wycheproof.txt", hdr, recs)
    return counts


def acvp(adir):
    root = os.path.join(adir, "gen-val/json-files")
    recs = []
    hdr = ["NIST ACVP-Server (usnistgov/ACVP-Server 975de31e) ML-KEM FIPS 203 internalProjection",
           "vectors, parameter set ML-KEM-768 only (notice: NIST.NOTICE). Generated by gen_vectors.py."]
    p = os.path.join(root, "ML-KEM-keyGen-FIPS203/internalProjection.json")
    hdr.append(f"ML-KEM-keyGen-FIPS203/internalProjection.json sha256 {sha256_file(p)}")
    groups = [g for g in json.load(open(p))["testGroups"] if g["parameterSet"] == "ML-KEM-768"]
    assert len(groups) == 1 and len(groups[0]["tests"]) == 25
    for t in groups[0]["tests"]:
        recs.append(f"K {t['d']} {t['z']} {t['ek']} {t['dk']}")
    p = os.path.join(root, "ML-KEM-encapDecap-FIPS203/internalProjection.json")
    hdr.append(f"ML-KEM-encapDecap-FIPS203/internalProjection.json sha256 {sha256_file(p)}")
    groups = [g for g in json.load(open(p))["testGroups"] if g["parameterSet"] == "ML-KEM-768"]
    want = {"encapsulation": 25, "decapsulation": 10, "decapsulationKeyCheck": 10,
            "encapsulationKeyCheck": 10}
    assert sorted(g["function"] for g in groups) == sorted(want)
    zc = "00" * CT
    for g in groups:
        assert len(g["tests"]) == want[g["function"]], g["function"]
        for t in g["tests"]:
            f = g["function"]
            if f == "encapsulation":
                recs.append(f"E 0 {t['ek']} {t['m']} {t['c']} {t['k']}")
                recs.append(f"D 0 {t['dk']} {t['c']} {t['k']}")
            elif f == "decapsulation":
                assert t["reason"] in ("valid decapsulation", "modified ciphertext")
                recs.append(f"D 0 {t['dk']} {t['c']} {t['k']}")
            elif f == "decapsulationKeyCheck":
                assert t["testPassed"] == (t["reason"] == "valid decapsulation key")
                assert t["testPassed"] or t["reason"] == "modified H"
                recs.append(f"D {0 if t['testPassed'] else 3} {t['dk']} {zc} -")
            else:
                assert t["testPassed"] or t["reason"] == "noisy linear system values too large"
                recs.append(f"E {0 if t['testPassed'] else 1} {t['ek']} {'00' * 32} - -")
    write("acvp.txt", hdr, recs)
    return len(recs)


def rsp(path, alg, outkey):
    """(msg hex, out hex) pairs of a CAVP byte-oriented .rsp; Len in bits, Msg 00 when Len = 0."""
    text = open(path).read()
    out, ln, msg = [], None, None
    for line in text.splitlines():
        m = re.match(r"^(Len|Msg|Outputlen|" + outkey + r") = (\S*)$", line.strip())
        if not m:
            continue
        k, v = m.groups()
        if k == "Len":
            ln = int(v)
        elif k == "Msg":
            msg = v
        elif k == outkey:
            if ln is not None:
                assert ln % 8 == 0
                msg = msg[:ln // 4]
            out.append(f"{alg} {hx(msg)} {v}")
            ln, msg = None, None
    return out


def nist(ndir):
    hdr = ["NIST CAVP SHA-3 / SHAKE byte-oriented vectors (sha-3bytetestvectors.zip,",
           "shakebytetestvectors.zip; notice: NIST.NOTICE). Generated by gen_vectors.py.",
           "H A MSG OUT: one-shot; S A MSG OUT: every 10th LongMsg vector again, chunked absorb/squeeze.",
           "A: 1 SHA3-256, 2 SHA3-512, 3 SHAKE128, 4 SHAKE256."]
    recs = []
    plan = [("SHA3_256ShortMsg.rsp", 1, "MD"), ("SHA3_256LongMsg.rsp", 1, "MD"),
            ("SHA3_512ShortMsg.rsp", 2, "MD"), ("SHA3_512LongMsg.rsp", 2, "MD"),
            ("SHAKE128ShortMsg.rsp", 3, "Output"), ("SHAKE128LongMsg.rsp", 3, "Output"),
            ("SHAKE128VariableOut.rsp", 3, "Output"),
            ("SHAKE256ShortMsg.rsp", 4, "Output"), ("SHAKE256LongMsg.rsp", 4, "Output"),
            ("SHAKE256VariableOut.rsp", 4, "Output")]
    # count per file = its Len = lines (COUNT = lines for VariableOut), counted independently of the parser
    for name, alg, key in plan:
        p = os.path.join(ndir, name)
        r = rsp(p, alg, key)
        hdr.append(f"{name} sha256 {sha256_file(p)} cases {len(r)}")
        n = len(re.findall(r"^COUNT = " if "VariableOut" in name else r"^Len = ", open(p).read(), re.M))
        assert len(r) == n and n > 0, (name, len(r), n)
        recs += ["H " + x for x in r]
        if "LongMsg" in name:
            recs += ["S " + x for x in r[::10]]  # every 10th long message, streamed
    write("nist-sha3.txt", hdr, recs)
    return len(recs)


if __name__ == "__main__":
    w, n, a = sys.argv[1:4]
    print(wycheproof(w))
    print(acvp(a))
    print(nist(n))
