# Test tooling only (security review of omega-mv #813, finding 8): writes vectors/dns.txt, crafted
# DNS responses for dnsunit.om. Each case line is "R IIIIIIII HOST HEX": R is 0 (dns_parse must
# return 0 and the address IIIIIIII) or E (it must return TLS_ERR_DNS, without trapping); HEX is
# the response to the query dns_query builds for HOST with id 0x4f4d. A "# name" comment precedes
# each case.
import os, struct

ID = 0x4F4D


def name(h):
    return b"".join(bytes([len(x)]) + x for x in h.encode().split(b".")) + b"\0"


def query(h):
    return struct.pack(">HHHHHH", ID, 0x0100, 1, 0, 0, 0) + name(h) + b"\0\1\0\1"


def rr(owner, ty, data, cls=1):
    return owner + struct.pack(">HHIH", ty, cls, 300, len(data)) + data


def resp(h, answers, flags=0x8180, qid=ID, qd=1, an=None, q=None):
    q = q if q is not None else query(h)[12:]
    an = len(answers) if an is None else an
    return struct.pack(">HHHHHH", qid, flags, qd, an, 0, 0) + q + b"".join(answers)


H = "www.example.test"
QN = b"\xc0\x0c"  # pointer to the question name
ip = lambda s: bytes(int(x) for x in s.split("."))
cases = []
add = lambda n, r, a, b, h=H: cases.append((n, r, a, h, b))

add("plain A", "0", "192.0.2.1", resp(H, [rr(QN, 1, ip("192.0.2.1"))]))
add("owner written out, other case", "0", "192.0.2.2", resp(H, [rr(name("WWW.Example.TEST"), 1, ip("192.0.2.2"))]))
# CNAME www -> edge.cdn.test (at offset 12+22+12 = 46 of the response), then A for the target
r1 = resp(H, [])
cn = rr(QN, 5, name("edge.cdn.test"))
tgt = len(r1) + 12
add("CNAME chain", "0", "198.51.100.7",
    resp(H, [cn, rr(bytes([0xC0 | tgt >> 8, tgt & 255]), 1, ip("198.51.100.7"))]))
add("A for another owner skipped", "0", "192.0.2.9",
    resp(H, [rr(name("evil.test"), 1, ip("203.0.113.66")), rr(QN, 1, ip("192.0.2.9"))]))
add("only an A for another owner", "E", "0.0.0.0", resp(H, [rr(name("evil.test"), 1, ip("203.0.113.66"))]))
add("A for the old name after a CNAME", "E", "0.0.0.0",
    resp(H, [rr(QN, 5, name("edge.cdn.test")), rr(QN, 1, ip("203.0.113.66"))]))
add("CNAME owned by another name ignored", "E", "0.0.0.0",
    resp(H, [rr(name("evil.test"), 5, name("www.example.test")), rr(name("evil.test"), 1, ip("203.0.113.66"))]))
add("owner with 200 labels", "E", "0.0.0.0", resp(H, [rr(b"\1a" * 200 + b"\0", 1, ip("203.0.113.66"))]))
add("owner with 127 labels then the real A", "0", "192.0.2.4",
    resp(H, [rr(b"\1a" * 126 + b"\0", 1, ip("203.0.113.66")), rr(QN, 1, ip("192.0.2.4"))]))
lp = len(r1)  # an owner that is a pointer to itself
add("self-pointer owner", "E", "0.0.0.0", resp(H, [rr(bytes([0xC0 | lp >> 8, lp & 255]), 1, ip("203.0.113.66"))]))
add("QR clear", "E", "0.0.0.0", resp(H, [rr(QN, 1, ip("203.0.113.66"))], flags=0x0180))
add("opcode 1", "E", "0.0.0.0", resp(H, [rr(QN, 1, ip("203.0.113.66"))], flags=0x8980))
add("TC set", "E", "0.0.0.0", resp(H, [rr(QN, 1, ip("203.0.113.66"))], flags=0x8380))
add("RCODE 3", "E", "0.0.0.0", resp(H, [rr(QN, 1, ip("203.0.113.66"))], flags=0x8183))
add("RCODE 2", "E", "0.0.0.0", resp(H, [rr(QN, 1, ip("203.0.113.66"))], flags=0x8182))
add("AA RD RA AD CD set", "0", "192.0.2.5", resp(H, [rr(QN, 1, ip("192.0.2.5"))], flags=0x85B0))
add("id mismatch", "E", "0.0.0.0", resp(H, [rr(QN, 1, ip("203.0.113.66"))], qid=ID ^ 1))
add("other question", "E", "0.0.0.0", resp(H, [rr(QN, 1, ip("203.0.113.66"))], q=query("www.example.tesu")[12:]))
add("no answers", "E", "0.0.0.0", resp(H, []))
add("rdata cut off", "E", "0.0.0.0", resp(H, [rr(QN, 1, ip("203.0.113.66"))])[:-2])
add("A with class CH", "E", "0.0.0.0", resp(H, [rr(QN, 1, ip("203.0.113.66"), cls=3)]))

here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "vectors", "dns.txt"), "w") as f:
    f.write("# generated by gen_dns.py: R IIIIIIII HOST HEX (dnsunit.om); L HOST = dns_a4 must refuse HOST\n")
    for n, r, a, h, b in cases:
        f.write(f"# {n}\n{r} {ip(a).hex()} {h} {b.hex()}\n")
    # security re-review N1: dns_a4 refuses a name over 253 bytes before building its 300-byte query
    longs = [(300, ("a" * 63 + ".") * 4 + "a" * 44), (254, ".".join(["a" * 63] * 4)[:254])]
    for k, h in longs:
        assert len(h) == k
        f.write(f"# dns_a4 name of {k} bytes\nL {h}\n")
print(len(cases) + len(longs), "cases")
