# OM-2 qualification, lane s5s7 (#748, ledger L836): independent expected values for the
# fixtures in sec/s5s7/. Run from the worktree root:
#   /usr/bin/python3 seed/qualification/om2/oracle/s5s7/oracle.py
# Writes seed/qualification/om2/oracle/s5s7/exp/* and sha/expected.h. Nothing here reads a
# compiler output; every value is computed from the contract's stated semantics.
import hashlib
import os
import struct

Q = "seed/qualification/om2/oracle/s5s7"
E = Q + "/exp"
M64 = (1 << 64) - 1
M32 = (1 << 32) - 1


def w(name, data):
    with open(os.path.join(E, name), "wb") as f:
        f.write(data)


def hexl(v):
    return ("%016x\n" % (v & M64)).encode()


def decl(v):
    return ("%d\n" % v).encode()


def rotr(x, n, wd):
    m = (1 << wd) - 1
    n %= wd
    return ((x >> n) | (x << (wd - n))) & m


def rotl(x, n, wd):
    return rotr(x, (wd - n) % wd, wd)


def dup(x):
    return ((x & M32) << 32) | (x & M32)


os.makedirs(E, exist_ok=True)

# contract 140-141: rotr/rotl of a dup32 value is a 64-bit rotation, equal to the dup of the
# 32-bit rotation by n mod 32. Both sides are computed and must agree.
X, Y, Z = 0x89ABCDEF, 0x01234567, 0x0F0F00FF
d = dup(X)
out = hexl(d) + hexl(d + 1)
for n in (0, 1, 8, 31, 32, 33, 63):
    a = rotr(d, n, 64)
    assert a == dup(rotr(X, n % 32, 32)), n
    out += hexl(a)
assert dup(X) ^ dup(Y) == dup(X ^ Y)
out += hexl(dup(X) ^ dup(Y))
w("a5-exact.out", out)

out = b""
for n in (8, 40):
    a = rotl(d, n, 64)
    assert a == dup(rotl(X, n % 32, 32)), n
    out += hexl(a)
e = dup(Z)
out += hexl(d & e) + hexl(d | e) + hexl(d ^ e)
a = rotr(d, 5, 64)
assert a == dup(rotr(X, 5, 32))
out += hexl(a)
w("a5-allops.out", out)

# kept-check mutant prediction (constructor body or shl ulong x 32 ulong add x 1, x = 5)
w("a5-kept.mutant", hexl((5 << 32) | 6))
# commuted exact body: or ulong x shl ulong x 32 == dup(x)
w("a5-swap.out", hexl(dup(0xDEADBEEF)))

# contract 163-165: shactx image; struct layout from sha256.h (uint32 state[8], uint64 count,
# uint8 buffer[64]) on LP64 AArch64 little endian. offsetof.c checks the same image with gcc.
img = b"".join(struct.pack("<I", 0x10203040 + i) for i in range(8))
img += struct.pack("<Q", 0x0123456789ABCDEF)
img += bytes((3 * j + 1) & 255 for j in range(64))
assert len(img) == 104
w("l5-shactx.out", img)

# endianness: layout be16 16 / fa uint 1 at 0 big / fb ulong 1 at 4 big / fc ushort 2 at 12 little
A, B, C0, C1 = 0x0A0B0C0D, 0x0102030405060708, 0xBEEF, 0x1234
img = struct.pack(">I", A) + struct.pack(">Q", B) + struct.pack("<HH", C0, C1)
assert len(img) == 16
w("l5-endian.out", img + hexl(A) + hexl(B) + hexl(C0) + hexl(C1))
w("l5-scalar.out", struct.pack(">I", 0x01020304) + hexl(0x01020304))

# section 6 views
s = sum(i * 7 for i in range(10))
w("v6-sum.out", decl(10) + decl(s) + decl(3) + decl(3 * 5))
row = bytearray(b"." * 10)
for i in range(3, 7):
    row[i] = ord("X")
w("v6-part-empty.out", decl(0))
w("v6-edit.out", decl(2) + bytes(row) + b"\n" + decl(4))
# wrapped-sum mutant: (2^64-2 + 4) mod 2^64 = 2 <= 10 accepts, callee prints len 4
assert (M64 - 1 + 4) & M64 == 2
w("v6-part-wrap.mutant", decl(4))
# second-check-dropped mutant on o = 8, k = 4: o <= 10 holds, callee prints 4
w("v6-part-tail.mutant", decl(4))
# first-check-dropped mutant on o = 11, k = 0: len - o wraps to 2^64-1 >= 0, callee prints 0
assert (10 - 11) & M64 == M64
w("v6-part-o.mutant", decl(0))

# section 5 fresh
w("f5-line.out", decl(42))
w("f5-unroll-all.out", decl(6) + decl(sum(range(1, 9))))
w("f5-n64.out", decl(64) + decl(sum(range(1, 65))))
w("f5-ifelse.out", decl(11) + decl(22))
w("f5-inline.out", decl(5 + 2) + decl(sum(i + 2 for i in range(8))))
w("f5-join-diff.mutant", decl(99))

# OM-1 names control (contract 15-16): at seal open abstract holds layout field little big part
# export out rotr hold 1..13; fresh is a parameter of a function named dup32mk
w("t-names.out", decl(sum(range(1, 14))) + hexl(dup(7)))

# section 7 SHA consumer expectations (C driver, NOT_RUN until the generated header exists)
def seq(n):
    return bytes(i % 251 for i in range(n))


def hx(b):
    return hashlib.sha256(b).hexdigest()


lines = ["/* generated by oracle.py (python3 hashlib); do not edit */"]
lines.append('#define EXP_EMPTY "%s"' % hx(b""))
lines.append('#define EXP_ABC "%s"' % hx(b"abc"))
lines.append('#define EXP_SEQ1000 "%s"' % hx(seq(1000)))
lines.append('#define EXP_SEQ64 "%s"' % hx(seq(64)))
ns = (0, 1, 55, 56, 63, 64, 65, 119, 120, 1000)
lines.append("static const unsigned long exp_hash_n[%d] = {%s};" % (len(ns), ", ".join(str(n) for n in ns)))
lines.append("static const char *const exp_hash_d[%d] = {" % len(ns))
for n in ns:
    lines.append('    "%s",' % hx(seq(n)))
lines.append("};")
BIG = (1 << 32) + 3
h = hashlib.sha256()
chunk = bytes(1 << 24)
left = BIG
while left:
    k = min(left, len(chunk))
    h.update(chunk[:k])
    left -= k
lines.append("#define EXP_BIG_LEN %dULL" % BIG)
lines.append('#define EXP_BIG_ZERO "%s"' % h.hexdigest())
with open(Q + "/sha/expected.h", "w") as f:
    f.write("\n".join(lines) + "\n")
print("oracle ok")
